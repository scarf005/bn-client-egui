use bn_client_egui::tint::tint_pixel;

#[test]
fn a_tinted_pixel_equals_the_games_blend() {
    // Values printed by the game's own hsv2rgb, rgb2hsv and tint blend (cata_tiles.cpp, hsv_color.cpp).
    let cases: [([u8; 3], [u8; 3], [u8; 3]); 28] = [
        ([200, 40, 40], [68, 85, 102], [129, 161, 194]),
        ([200, 40, 40], [255, 0, 0], [227, 22, 22]),
        ([200, 40, 40], [98, 38, 37], [194, 74, 73]),
        ([200, 40, 40], [200, 200, 200], [215, 215, 215]),
        ([120, 30, 30], [68, 85, 102], [72, 90, 108]),
        ([120, 30, 30], [255, 0, 0], [179, 22, 22]),
        ([120, 30, 30], [98, 38, 37], [106, 41, 40]),
        ([120, 30, 30], [200, 200, 200], [153, 153, 153]),
        ([255, 255, 255], [68, 85, 102], [212, 233, 255]),
        ([255, 255, 255], [255, 0, 0], [255, 128, 128]),
        ([255, 255, 255], [98, 38, 37], [255, 176, 175]),
        ([255, 255, 255], [200, 200, 200], [255, 255, 255]),
        ([10, 10, 10], [68, 85, 102], [7, 8, 9]),
        ([10, 10, 10], [255, 0, 0], [14, 7, 7]),
        ([10, 10, 10], [98, 38, 37], [8, 5, 5]),
        ([10, 10, 10], [200, 200, 200], [12, 12, 12]),
        ([90, 160, 200], [68, 85, 102], [129, 161, 194]),
        ([90, 160, 200], [255, 0, 0], [227, 51, 51]),
        ([90, 160, 200], [98, 38, 37], [194, 81, 80]),
        ([90, 160, 200], [200, 200, 200], [215, 215, 215]),
        ([128, 128, 128], [68, 85, 102], [95, 105, 115]),
        ([128, 128, 128], [255, 0, 0], [190, 95, 95]),
        ([128, 128, 128], [98, 38, 37], [113, 77, 77]),
        ([128, 128, 128], [200, 200, 200], [163, 163, 163]),
        ([250, 240, 20], [68, 85, 102], [166, 207, 249]),
        ([250, 240, 20], [255, 0, 0], [252, 10, 10]),
        ([250, 240, 20], [98, 38, 37], [249, 96, 94]),
        ([250, 240, 20], [200, 200, 200], [251, 251, 251]),
    ];
    for (base, paint, expected) in cases {
        assert_eq!(
            tint_pixel(base, paint),
            expected,
            "{base:?} painted {paint:?}"
        );
    }
}
