use bn_client_egui::tint::{Blend, Paint, tint_pixel};

type Pixel = [u8; 3];
/// A sprite pixel, its paint, its mask pixel and the result the game prints.
type Masked = (Pixel, Pixel, Pixel, Pixel);
type Blended = (Blend, Pixel, Pixel, Pixel, Pixel);

