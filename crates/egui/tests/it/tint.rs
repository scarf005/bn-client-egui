#[test]
fn contrast_saturation_and_brightness_adjust_the_result_like_the_game() {
    let cases: [([u8; 3], [u8; 3]); 4] = [
        ([200, 40, 40], [72, 10, 0]),
        ([12, 34, 38], [0, 0, 0]),
        ([128, 128, 128], [40, 29, 0]),
        ([250, 240, 20], [95, 67, 0]),
    ];
    let paint = Paint {
        blend: Blend::Multiply,
        contrast: 1250,
        saturation: 1500,
        brightness: 500,
        ..Paint::of([183, 136, 0])
    };
    for (base, expected) in cases {
        assert_eq!(
            tint_pixel(base, paint, Some([255, 127, 127])),
            expected,
            "{base:?}"
        );
    }
}
