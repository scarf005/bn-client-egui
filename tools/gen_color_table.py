#!/usr/bin/env python3
"""Regenerates src/color_table.rs from the game's src/color.cpp.
usage: tools/gen_color_table.py /path/to/Cataclysm-BN/src/color.cpp > src/color_table.rs"""
import re
import sys

src = open(sys.argv[1]).read()
index = {"black": 0, "red": 1, "green": 2, "blue": 4, "cyan": 6, "magenta": 5, "yellow": 3, "white": 7}
pairs = {int(a): (index[b], index[c]) for a, b, c in re.findall(r"init_pair\(\s*(\d+),\s*(\w+),\s*(\w+)\s*\)", src)}
rows = []
for name, pair, attrs in re.findall(r'add_color\(\s*\w+,\s*"(\w+)",\s*color_pair\(\s*(\d+)\s*\)((?:\.\w+\(\))*)', src):
    fg, bg = pairs[int(pair)]
    rows.append((name, fg + (8 if ".bold()" in attrs else 0), bg))
print("// Generated by tools/gen_color_table.py from src/color.cpp (add_color + init_pair); do not edit.")
print("// (name, foreground palette index 0..15, background palette index 0..7)")
print("pub const NAMED: &[(&str, u8, u8)] = &[")
for r in rows:
    print(f'    ("{r[0]}", {r[1]}, {r[2]}),')
print("];")
